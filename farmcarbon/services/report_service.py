def esc(value):
    return escape(str(value if value is not None else "—"))

DISCLAIMER = ("This document is an independent monitoring and analytical report generated by FarmCarbon MRV. "
"Any carbon-stock changes are calculated from the measurements and assumptions recorded in the application. "
"Satellite indicators provide supporting environmental information and do not independently establish soil-carbon removal. "
"This report is not a third-party verification statement, carbon-credit certification, registry issuance, or guarantee "
"of additionality, permanence, or ownership.")


def _boundary_drawing(geometry):
    if not geometry:
        return None
    geom_type = geometry.get("type")
    coords = geometry.get("coordinates") or []
    rings = []
    if geom_type == "Polygon" and coords:
        rings = [coords[0]]
    elif geom_type == "MultiPolygon":
        rings = [polygon[0] for polygon in coords if polygon]
    points = [(float(x), float(y)) for ring in rings for x, y, *_ in ring]
    if not points:
        return None
    min_x, max_x = min(x for x, _ in points), max(x for x, _ in points)
    min_y, max_y = min(y for _, y in points), max(y for _, y in points)
    width, height = 420, 170
    sx = (width - 48) / max(max_x - min_x, 1e-9)
    sy = (height - 48) / max(max_y - min_y, 1e-9)
    scale = min(sx, sy)
    drawing = Drawing(width, height)
    drawing.add(Rect(8, 8, width - 16, height - 16, fillColor=colors.HexColor("#F6F8F6"), strokeColor=colors.HexColor("#D7E1D9")))
    for ring in rings:
        transformed = []
        for x, y, *_ in ring:
            px = 24 + (float(x) - min_x) * scale
            py = 24 + (float(y) - min_y) * scale
            transformed.extend([px, py])
        if len(transformed) >= 6:
            drawing.add(PolyLine(transformed, strokeColor=colors.HexColor("#174D38"), strokeWidth=2, fillColor=colors.HexColor("#DDEBE1"), closeFirst=False, closeLast=True))
    drawing.add(String(16, 14, "Farm boundary (schematic from stored GeoJSON)", fontSize=7, fillColor=colors.HexColor("#52645A")))
    return drawing


def _index_chart_drawing(observations):
    if not observations:
        return None
    ordered = sorted(observations, key=lambda row: row.get("observation_date", ""))
    drawing = Drawing(440, 205)
    x0, y0, chart_w, chart_h = 42, 35, 370, 130
    drawing.add(Rect(0, 0, 440, 205, fillColor=colors.white, strokeColor=colors.HexColor("#E1E8E2")))
    all_values = [float(row[key]) for row in ordered for key in ("ndvi", "ndmi", "evi") if row.get(key) is not None]
    low = min(-0.2, min(all_values)) if all_values else -0.2
    high = max(1.0, max(all_values)) if all_values else 1.0
    if high - low < 0.05:
        high = low + 0.05
    for tick in range(5):
        y = y0 + chart_h * tick / 4
        drawing.add(Line(x0, y, x0 + chart_w, y, strokeColor=colors.HexColor("#E8EDE9"), strokeWidth=0.5))
        val = low + (high - low) * tick / 4
        drawing.add(String(5, y - 2, f"{val:.1f}", fontSize=7, fillColor=colors.HexColor("#5C6C62")))
    palette = {"ndvi": colors.HexColor("#174D38"), "ndmi": colors.HexColor("#3B82A0"), "evi": colors.HexColor("#C18A36")}
    for key, color in palette.items():
        coords = []
        for i, row in enumerate(ordered):
            if row.get(key) is None:
                continue
            x = x0 + (chart_w * i / max(len(ordered) - 1, 1))
            y = y0 + (float(row[key]) - low) / (high - low) * chart_h
            coords.extend([x, y])
        if len(coords) >= 4:
            drawing.add(PolyLine(coords, strokeColor=color, strokeWidth=1.6))
    drawing.add(String(x0, 12, str(ordered[0].get("observation_date", "")), fontSize=7, fillColor=colors.HexColor("#52645A")))
    drawing.add(String(x0 + chart_w - 56, 12, str(ordered[-1].get("observation_date", "")), fontSize=7, fillColor=colors.HexColor("#52645A")))
    for i, (label, color) in enumerate((("NDVI", palette["ndvi"]), ("NDMI", palette["ndmi"]), ("EVI", palette["evi"]))):
        drawing.add(Line(90 + i * 95, 187, 107 + i * 95, 187, strokeColor=color, strokeWidth=2))
        drawing.add(String(111 + i * 95, 184, label, fontSize=8, fillColor=colors.HexColor("#33443A")))
    drawing.add(String(8, 197, "Satellite index history (source mode is shown in the accompanying table)", fontSize=8, fillColor=colors.HexColor("#33443A")))
    return drawing


def generate_farm_pdf(farm, soils, observations, practices, evidence, assessment) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm, topMargin=17*mm, bottomMargin=17*mm)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="FarmTitle", parent=styles["Title"], textColor=colors.HexColor("#174D38"), fontSize=23, leading=28))
    observation_dates = [str(o.get("observation_date")) for o in observations if o.get("observation_date")]
    reporting_start = min(observation_dates) if observation_dates else (farm.get("project_start_date") or "Not recorded")
    reporting_end = max(observation_dates) if observation_dates else __import__("datetime").date.today().isoformat()
    story = [Paragraph("FarmCarbon MRV", styles["FarmTitle"]), Paragraph("Agricultural Carbon Monitoring Report", styles["Heading2"]), Spacer(1, 8*mm),
        Paragraph(f"<b>Farm:</b> {esc(farm.get('name','—'))}", styles["Normal"]),
        Paragraph(f"<b>Project identifier:</b> {esc(farm.get('project_identifier') or '—')}", styles["Normal"]),
        Paragraph(f"<b>Reporting period:</b> {esc(reporting_start)} to {esc(reporting_end)}", styles["Normal"]),
        Paragraph(f"<b>Report generated:</b> {__import__('datetime').date.today().isoformat()}", styles["Normal"]),
        Paragraph(f"<b>Monitoring status:</b> {assessment['status']} | <b>Completeness:</b> {assessment['completeness_score']}%", styles["Normal"]), PageBreak()]
    def section(title, body):
        story.append(Paragraph(title, styles["Heading2"]))
        story.append(Paragraph(body, styles["BodyText"]))
        story.append(Spacer(1, 4*mm))
    section("1. Project Overview", f"Location: {esc(farm.get('village') or '—')}, {esc(farm.get('district') or '—')}, {esc(farm.get('state') or '—')}, {esc(farm.get('country') or '—')}<br/>Area: {farm.get('area_ha') or 0:.4f} ha<br/>Crop: {esc(farm.get('crop') or '—')}<br/>Soil type: {esc(farm.get('soil_type') or '—')}<br/>Project start: {farm.get('project_start_date') or '—'}<br/>Baseline date: {farm.get('baseline_date') or '—'}<br/>Description: {esc(farm.get('description') or '—')}")
    section("2. Farm Boundaries", "A GeoJSON boundary is stored." if farm.get("boundary_geojson") else "No farm boundary has been provided. Area/coordinates may be manually entered.")
    story.append(Paragraph(f"Centroid: {farm.get('latitude') or '—'}, {farm.get('longitude') or '—'}", styles["BodyText"]))
    boundary_chart = _boundary_drawing(farm.get("boundary_geojson"))
    if boundary_chart:
        story.append(boundary_chart)
        story.append(Spacer(1, 4*mm))
    cloud_values = [float(o.get("cloud_percentage")) for o in observations if o.get("cloud_percentage") is not None]
    mean_cloud = sum(cloud_values) / len(cloud_values) if cloud_values else None
    section("3. Monitoring Activity", f"Stored observations: {len(observations)}. Mean scene cloud cover: {f'{mean_cloud:.1f}%' if mean_cloud is not None else 'not available'}. Sources: {esc(', '.join(sorted({str(o.get('source','unknown')) for o in observations})) or 'None')}. NDVI/NDMI/EVI describe vegetation and surface moisture conditions; they are not direct soil-carbon measurements.")
    trend_chart = _index_chart_drawing(observations)
    if trend_chart:
        story.append(trend_chart)
        story.append(Spacer(1, 3*mm))
    if observations:
        rows = [["Date", "NDVI", "NDMI", "EVI", "Cloud %", "Mode"]]
        for o in sorted(observations, key=lambda x: x.get("observation_date", ""))[-20:]:
            rows.append([o.get("observation_date"), o.get("ndvi"), o.get("ndmi"), o.get("evi"), o.get("cloud_percentage"), o.get("source_mode")])
        t = Table(rows, repeatRows=1, colWidths=[27*mm, 19*mm, 19*mm, 19*mm, 22*mm, 18*mm])
        t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#E7F0EA")),("GRID",(0,0),(-1,-1),0.3,colors.grey),("FONTSIZE",(0,0),(-1,-1),7),("PADDING",(0,0),(-1,-1),4)]))
        story.append(t)
    story.append(Spacer(1, 5*mm))
    comparison = compare_samples(soils, farm.get("area_ha"))
    section("4. Soil Organic Carbon", f"Soil samples recorded: {len(soils)}. Fixed-depth SOC stock calculation: SOC (g/kg) × bulk density (g/cm³) × (1 − coarse fragment fraction) × depth (cm) × 0.1 = Mg C/ha. Comparisons require same farm, zone, depth interval and measurement method.")
    if soils:
        rows = [["Sample", "Period", "Zone", "Depth cm", "SOC g/kg", "Stock Mg C/ha"]]
        for s in soils:
            rows.append([s.get("sample_identifier"),s.get("measurement_period"),s.get("zone_id"),f"{s.get('depth_top_cm')}-{s.get('depth_bottom_cm')}",s.get("soc_g_kg"),s.get("calculated_soc_stock_mg_c_ha")])
        t = Table(rows, repeatRows=1, colWidths=[27*mm,22*mm,18*mm,23*mm,20*mm,35*mm])
        t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#E7F0EA")),("GRID",(0,0),(-1,-1),0.3,colors.grey),("FONTSIZE",(0,0),(-1,-1),7),("PADDING",(0,0),(-1,-1),4)]))
        story.append(t)
    for item in comparison["comparisons"]:
        section(f"Zone {esc(item['zone_id'])} comparison", f"Baseline: {item['baseline_stock_mg_c_ha']:.3f} Mg C/ha; follow-up: {item['followup_stock_mg_c_ha']:.3f} Mg C/ha; change: {item['stock_change_mg_c_ha']:.3f} Mg C/ha; zone area: {item['zone_area_ha'] if item['zone_area_ha'] is not None else 'not provided'} ha; CO2e equivalent: {item['co2e_change_mg'] if item['co2e_change_mg'] is not None else 'not calculated'} Mg CO2e.")
    section("5. Agricultural Interventions", f"Interventions recorded: {len(practices)}; evidence files registered: {len(evidence)}.")
    if practices:
        for p in practices:
            story.append(Paragraph(f"• {esc(p.get('practice_type'))} | {esc(p.get('start_date'))} | {esc(p.get('area_ha'))} ha | {esc(p.get('status'))}", styles["BodyText"]))
    section("6. MRV Data Quality", "<br/>".join(f"• {esc(w)}" for w in assessment["warnings"]) or "No automated warnings generated.")
    section("7. Results", f"Completeness indicator: {assessment['completeness_score']}% (project-management indicator, not a scientific confidence score).<br/>Comparable zones: {len(comparison['comparisons'])}.<br/>Total carbon stock change: {comparison['total_carbon_stock_change_mg_c'] if comparison['total_carbon_stock_change_mg_c'] is not None else 'Not calculated'} Mg C.<br/>CO2e equivalent: {comparison['total_co2e_change_mg'] if comparison['total_co2e_change_mg'] is not None else 'Not calculated'} Mg CO2e.")
    section("Limitations", "Results use a fixed-depth calculation. Equivalent soil mass adjustment is not implemented and may be necessary when bulk density differs. No carbon-credit quantity or certified removal is asserted. Synthetic or uploaded observations are identified by source mode in the underlying records.")
    section("8. Disclaimer", DISCLAIMER)
    doc.build(story)
    return buffer.getvalue()
